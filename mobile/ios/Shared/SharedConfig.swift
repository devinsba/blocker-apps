import BlockerKit
import Foundation

/// Config shared between the app and its network extensions through the App Group.
///
/// Layout of the group container:
///
///     Blocker/
///       config.toml   the config every BlockerEngine is compiled from (extensions read this)
///       rules.json    the app's editable copy of the rules (source of truth for the UI)
///       lists/        downloaded category lists (<category>.fst), not fetched yet on iOS
///
/// Why two files: blocker-ffi can validate and compile config.toml but does not
/// expose a TOML -> JSON reader, so the app keeps its own model as JSON and
/// renders config.toml from it (see `RuleModel.renderConfigTOML`).
public enum SharedConfig {
    /// Must match the `com.apple.security.application-groups` entitlement of every target.
    public static let appGroupID = "group.dev.blocker.shared"

    /// `vendorConfiguration` key the app uses to hand config.toml to the content filter,
    /// whose sandbox may not be able to read the group container.
    public static let vendorConfigKey = "configTOML"

    public static var directory: URL {
        let base = FileManager.default.containerURL(forSecurityApplicationGroupIdentifier: appGroupID)
            // No App Group entitlement (e.g. SwiftUI previews): fall back to Application Support.
            ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return base.appendingPathComponent("Blocker", isDirectory: true)
    }

    public static var configURL: URL { directory.appendingPathComponent("config.toml") }
    public static var rulesURL: URL { directory.appendingPathComponent("rules.json") }

    public static func readConfigTOML() -> String? {
        try? String(contentsOf: configURL, encoding: .utf8)
    }

    /// Validates `toml` with blocker-core, then replaces config.toml atomically.
    public static func writeConfigTOML(_ toml: String) throws {
        try BlockerEngine.validateConfig(toml)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        try Data(toml.utf8).write(to: configURL, options: .atomic)
    }

    /// Compiles the shared config directory (config.toml + lists/).
    public static func loadEngine() throws -> BlockerEngine {
        try BlockerEngine(directory: directory)
    }
}

/// One `[[rule]]` of config.toml, in the subset the iOS app edits.
public struct RuleModel: Codable, Hashable, Identifiable, Sendable {
    public var id: String { name }
    public var name: String
    public var enabled: Bool = true
    public var locked: Bool = false
    public var domains: [String] = []
    public var categories: [String] = []
    public var bundleIDs: [String] = []
    /// nil = always active.
    public var window: DailyWindow?

    public init(name: String, enabled: Bool = true, locked: Bool = false, domains: [String] = [],
                categories: [String] = [], bundleIDs: [String] = [], window: DailyWindow? = nil) {
        self.name = name
        self.enabled = enabled
        self.locked = locked
        self.domains = domains
        self.categories = categories
        self.bundleIDs = bundleIDs
        self.window = window
    }

    /// A window on the given weekdays (0 = Mon ... 6 = Sun; empty = every day).
    public struct DailyWindow: Codable, Hashable, Sendable {
        public var days: [Int]
        public var startMinute: Int
        public var endMinute: Int

        public init(days: [Int], startMinute: Int, endMinute: Int) {
            self.days = days
            self.startMinute = startMinute
            self.endMinute = endMinute
        }
    }

    public static let sample: [RuleModel] = [
        RuleModel(name: "focus", domains: ["reddit.com", "news.ycombinator.com", "x.com"]),
        RuleModel(
            name: "work-hours",
            domains: ["youtube.com", "twitch.tv"],
            window: DailyWindow(days: [0, 1, 2, 3, 4], startMinute: 9 * 60, endMinute: 17 * 60)
        ),
    ]

    /// Renders `rules` as config.toml text.
    public static func renderConfigTOML(_ rules: [RuleModel]) -> String {
        var out = "# Generated by the Blocker iOS app from rules.json. Edits here are overwritten.\n"
        for rule in rules {
            out += "\n[[rule]]\n"
            out += "name = \(quote(rule.name))\n"
            if !rule.enabled { out += "enabled = false\n" }
            if rule.locked { out += "locked = true\n" }
            if !rule.domains.isEmpty { out += "domains = \(array(rule.domains))\n" }
            if !rule.categories.isEmpty { out += "categories = \(array(rule.categories))\n" }
            if !rule.bundleIDs.isEmpty { out += "bundle_ids = \(array(rule.bundleIDs))\n" }
            if let w = rule.window {
                let dayNames = ["mon", "tue", "wed", "thu", "fri", "sat", "sun"]
                let days = array(w.days.filter { (0...6).contains($0) }.map { dayNames[$0] })
                out += "schedule = { type = \"windows\", windows = [{ days = \(days), "
                    + "start = \(quote(hhmm(w.startMinute))), end = \(quote(hhmm(w.endMinute))) }] }\n"
            }
        }
        return out
    }

    private static func hhmm(_ m: Int) -> String {
        String(format: "%02d:%02d", (m / 60) % 24, m % 60)
    }

    private static func array(_ items: [String]) -> String {
        "[" + items.map(quote).joined(separator: ", ") + "]"
    }

    /// TOML basic string.
    private static func quote(_ s: String) -> String {
        var out = "\""
        for scalar in s.unicodeScalars {
            switch scalar {
            case "\"": out += "\\\""
            case "\\": out += "\\\\"
            case "\n": out += "\\n"
            case "\t": out += "\\t"
            case "\r": out += "\\r"
            default:
                if scalar.value < 0x20 || scalar.value == 0x7f {
                    out += String(format: "\\u%04X", scalar.value)
                } else {
                    out.unicodeScalars.append(scalar)
                }
            }
        }
        return out + "\""
    }
}
